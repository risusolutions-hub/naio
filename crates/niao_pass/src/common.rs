pub fn is_common_password(password: &str) -> bool {
    let lower = password.to_ascii_lowercase();
    COMMON.iter().any(|&p| p == lower)
}

pub fn char_classes(password: &str) -> CharClasses {
    let mut classes = CharClasses {
        upper: 0,
        lower: 0,
        digit: 0,
        special: 0,
        other: 0,
    };
    for ch in password.chars() {
        if ch.is_ascii_uppercase() {
            classes.upper += 1;
        } else if ch.is_ascii_lowercase() {
            classes.lower += 1;
        } else if ch.is_ascii_digit() {
            classes.digit += 1;
        } else if ch.is_ascii_punctuation() || ch.is_ascii_whitespace() {
            classes.special += 1;
        } else {
            classes.other += 1;
        }
    }
    classes
}

pub fn shannon_entropy(password: &str) -> f64 {
    if password.is_empty() {
        return 0.0;
    }
    let mut freq = [0u32; 256];
    let bytes = password.as_bytes();
    for &b in bytes {
        freq[b as usize] += 1;
    }
    let len = bytes.len() as f64;
    freq.iter()
        .filter(|&&c| c > 0)
        .map(|&c| {
            let p = c as f64 / len;
            -p * p.log2()
        })
        .sum::<f64>()
        * len.log2().max(1.0)
        / (bytes.len() as f64).log2().max(1.0)
}
